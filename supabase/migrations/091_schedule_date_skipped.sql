-- 091: 일정 날짜에 '미실시(스킵)' 표시 추가
--
-- 문제: 휴관 등으로 실제로 안 모인 주가 있는데, 그 날짜를 일정에서 지워도
--   '자동 일정 등록'을 누르면 start_date 부터 매주 다시 만들어져 되살아난다.
--   auto 라우트가 "이미 있는 날짜"만 건너뛰기 때문에, 지운 날짜는 매번 부활한다.
--   운영진 입장에서는 지워도 지워도 다시 생기는 유령 일정이다.
--
-- 해결: 지우는 대신 표시를 남긴다. 행이 남아 있으면 자동 등록이 건너뛴다.
--   화면에서는 '미실시'로 구분해 보여주고, 영상 연동 대상에서도 뺀다.
--
-- 자동 판정 기준(운영 중 코드에서 수행):
--   영상 0개 AND 시작된 경기 0개 AND 날짜가 7일 이상 지남 → 미실시
--   ⚠ '시작된 경기 0개'를 반드시 함께 본다. 영상만 없는 날(경기는 했는데 업로드가 늦은 날)까지
--     미실시로 접으면, 실제로 치른 라운드가 화면에서 사라지고 영상 연동 대상에서도 빠진다.
--     영상은 나중에 올라올 수 있지만 기록은 이미 남아 있다.

ALTER TABLE public.league_schedule_dates
  ADD COLUMN IF NOT EXISTS is_skipped boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.league_schedule_dates.is_skipped IS
  '미실시(휴관 등). true 면 자동 일정 등록이 다시 만들지 않고, 영상 연동 대상에서도 제외한다.';
