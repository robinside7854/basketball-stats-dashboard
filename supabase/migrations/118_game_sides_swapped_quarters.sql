-- =============================================
-- 118_game_sides_swapped_quarters.sql
-- 쿼터마다 코트 좌우가 바뀐다 — 화면 배치를 그 쿼터에 맞춘다
-- =============================================
-- 배경
--   같은 경기라도 쿼터마다 두 팀의 코트 좌우가 바뀐다. 기록원은 영상을 보며 기록하는데
--   화면의 홈(왼쪽)·어웨이(오른쪽) 배치가 영상과 반대면 매번 머리로 뒤집어 눌러야 한다.
--   지금까지 있던 ⇄ 는 **경기 단위**라(league_games 의 home/away 를 실제로 맞바꾼다)
--   쿼터마다 쓸 수 없고, 기록이 시작된 뒤에는 아예 막혀 있다.
--
-- 모양
--   [2, 4]  — 2·4쿼터에서는 화면 좌우를 뒤집어 그린다. 없거나 NULL 이면 전 쿼터 기존 배치.
--
-- ⚠ 이것은 **표시 전용**이다. home_team_id / away_team_id 는 건드리지 않는다.
--   기록(league_game_events)은 선수의 team_id 로 저장되고 점수도 team_id 비교로 붙으므로,
--   화면만 뒤집어도 스탯·점수는 한 건도 달라지지 않는다. 반대로 이 값을 보고
--   home_team_id 를 바꾸는 코드를 쓰면 그 순간 과거 기록의 홈·원정이 통째로 어긋난다.
--
-- 왜 별도 표가 아니라 JSONB 인가
--   113(plus_one_quarters)과 같은 이유다. 기록 화면은 이미 league_games 행을 통째로 읽는다.
--   표를 따로 만들면 슬롯을 읽는 모든 경로가 조회를 하나씩 더 해야 하고, 하나라도 빠뜨리면
--   그 화면만 조용히 안 뒤집힌 채로 남는다.
-- =============================================

ALTER TABLE league_games ADD COLUMN IF NOT EXISTS sides_swapped_quarters JSONB;

COMMENT ON COLUMN league_games.sides_swapped_quarters IS
  '화면 좌우를 뒤집어 그릴 쿼터 목록. [2,4] 형태. 표시 전용이며 home_team_id/away_team_id 와 기록·점수에는 영향이 없다.';
