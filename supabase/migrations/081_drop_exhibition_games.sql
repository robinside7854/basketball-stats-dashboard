-- =============================================
-- 081_drop_exhibition_games.sql
-- 친선전(exhibition) 기능 제거 — 남은 빈 경기 정리
-- =============================================
-- 배경
--   친선전은 "외부 팀과 하는 경기"를 뜻하는데, 이 기능은 내부 인원을 2팀으로
--   나눠 경기 슬롯을 만드는 동작이라 개념이 어긋나 있었다.
--   대회형(mode='tournament')이 외부 상대를 정식으로 다루므로 친선전은 불필요하다.
--   사용자 판단으로 기능을 제거한다 (2026-08-04).
--
-- 삭제 대상
--   미라클 2026-05-09 의 친선 슬롯 8건. 사전 확인 결과 **이벤트 0건** — 만들어만 두고
--   기록하지 않은 빈 껍데기라 손실되는 기록이 없다.
--
-- ⚠️ league_games.is_exhibition 컬럼은 **남긴다.**
--   읽기 경로 10여 곳이 `.eq('is_exhibition', false)` 로 걸러내고 있는데,
--   컬럼을 지우면 그 쿼리들이 전부 런타임에서 깨진다(문자열 쿼리라 타입 체커가 못 잡는다).
--   행이 0건이 된 이상 이 필터들은 무해한 no-op 이며, 방어적으로 남겨 둔다.
--   정리는 레거시 트리 제거(단계 6) 때 한 번에 한다.
--
-- 함께 제거된 코드
--   · API   : /api/leagues/[id]/exhibition/init
--   · UI    : 일정 화면의 "친선전 추가" 버튼 + addExhibitionDate 핸들러
-- =============================================

-- 이벤트가 달린 친선 경기가 있으면 삭제하지 않는다 — 기록 손실 방지 가드.
DELETE FROM league_games g
 WHERE g.is_exhibition = true
   AND NOT EXISTS (
     SELECT 1 FROM league_game_events e WHERE e.league_game_id = g.id
   );
