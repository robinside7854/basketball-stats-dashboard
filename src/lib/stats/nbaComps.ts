export const NBA_AXIS_LABELS = ['공격', '수비', '리바운드', '슈팅', '리딩', '효율'] as const

export type NbaMatch = { comp: NbaComp; score: number; strengths: string[]; shotStyle: string | null }

/** 슛 분포를 비교할 최소 야투 시도 — 이보다 적으면 비중이 흔들려 쓰지 않는다 */
export const MIN_SHOT_FGA = 20
const SHOT_LABELS = ['레이업', '포스트', '미드', '3점'] as const

/** 우리 선수 슛 시도 수 [레이업, 포스트, 미드, 3점] → 비중(합 100). 시도가 적으면 null */
export function shotMix(attempts: readonly number[] | null | undefined): NbaShots | null {
  if (!attempts || attempts.length !== 4) return null
  const total = attempts.reduce((s, v) => s + v, 0)
  if (total < MIN_SHOT_FGA) return null
  return attempts.map(v => (v / total) * 100) as NbaShots
}

/** 우리 선수 6축(null 허용) → 닮은 NBA 선수 n명. 비교할 축이 4개 미만이면 빈 배열 */
/** position = 우리 선수 포지션 그룹('G'|'F'|'C') — 주면 그 포지션을 뛰는 NBA 선수만 비교한다. 없으면 전원 */
export function matchNbaComps(mine: readonly (number | null)[], n = 3, pool: readonly NbaComp[] = NBA_POOL, shots: NbaShots | null = null, position: 'G' | 'F' | 'C' | null = null): NbaMatch[] {
  if (position) pool = pool.filter(c => (NBA_POSITIONS[c.name] ?? '').includes(position))
  const idx = mine.map((v, i) => (v == null || !Number.isFinite(v) ? -1 : i)).filter(i => i >= 0)
  if (idx.length < 4) return []
  const a = idx.map(i => mine[i] as number)
  const ma = a.reduce((s, v) => s + v, 0) / a.length
  const ca = a.map(v => v - ma)
  const na = Math.hypot(...ca)
  // 강점 = 내 평균보다 10 이상 높은 축 — 「왜 닮았나」 한 줄
  const myStrong = new Set(idx.filter(i => (mine[i] as number) - ma >= 10))

  const scored = pool.map(comp => {
    const b = idx.map(i => comp.axes[i])
    const mb = b.reduce((s, v) => s + v, 0) / b.length
    const cb = b.map(v => v - mb)
    const nb = Math.hypot(...cb)
    // 둘 다 고른 모양(편차 거의 0)이면 모양은 중립(0.5)으로 둔다
    const shape = na < 1e-6 || nb < 1e-6 ? 0.5 : (ca.reduce((s, v, k) => s + v * cb[k], 0) / (na * nb) + 1) / 2
    const rmse = Math.sqrt(a.reduce((s, v, k) => s + (v - b[k]) ** 2, 0) / a.length)
    const level = Math.max(0, 1 - rmse / 50)
    let score: number
    let shotStyle: string | null = null
    if (shots) {
      const overlap = 1 - shots.reduce((s, v, k) => s + Math.abs(v - comp.shots[k]), 0) / 200
      score = Math.round((0.45 * shape + 0.3 * overlap + 0.25 * level) * 100)
      // 둘 다 가장 많이 쏘는 슛이 같으면 한 줄 이유에 붙인다
      const top = (v: readonly number[]) => v.indexOf(Math.max(...v))
      if (top(shots) === top(comp.shots)) shotStyle = `${SHOT_LABELS[top(shots)]} 위주`
    } else {
      score = Math.round((0.6 * shape + 0.4 * level) * 100)
    }
    const strengths = idx.filter(i => myStrong.has(i) && comp.axes[i] - mb >= 10).map(i => NBA_AXIS_LABELS[i])
    return { comp, score, strengths, shotStyle }
  })
  return scored.sort((x, y) => y.score - x.score || x.comp.name.localeCompare(y.comp.name, 'ko')).slice(0, n)
}
