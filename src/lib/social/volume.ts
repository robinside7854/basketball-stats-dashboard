// 인스타 매거진 VOL 번호 자동 채번.
//
// 규칙(2026-08-10 사용자 확정): **라운드(경기일) 1회당 +1**.
//
// ⚠ 중요한 사실: 완료된 라운드는 30회가 넘는데 최신 발행본이 VOL.3 이다. 즉 **매 라운드마다
// 발행해 온 게 아니라 최근에 발행을 시작했다.** 그래서 "라운드당 +1"은 앞으로의 규칙이지
// 과거에 소급할 수 있는 규칙이 아니다 — 기준일보다 앞선 라운드는 번호를 만들어 내지 않고
// null 을 돌려준다. (처음 구현은 1로 바닥을 눌러서, 7월 라운드를 고르면 전부 "VOL.1"이라는
// 틀린 확신을 줬다.)
//
// 왜 표를 안 만들었나: 규칙이 "라운드당 +1"이면 번호는 완료된 라운드 목록만으로 계산된다.
// 발행 이력을 따로 저장하면 그 표와 실제 라운드가 어긋날 때 어느 쪽이 맞는지 알 수 없게 되고,
// 그 어긋남은 조용히 생긴다. 계산으로 뽑으면 기준점 하나만 맞으면 항상 맞는다.
//
// 기준점: 사용자가 "최근 VOL.3 발행"이라고 확인해 준 시점의 최신 완료 라운드가 2026-08-08.
// 어긋나면 아래 두 줄만 고친다 — 화면의 VOL 입력란은 살려 뒀으므로 손으로 덮어쓸 수도 있다.
const VOL_BASE_DATE = '2026-08-08'
const VOL_BASE_NUMBER = 3

/**
 * 그 라운드에 매길 VOL 번호. 번호를 정할 근거가 없으면 null(화면은 빈칸으로 두고 직접 입력).
 *
 * @param date       대상 라운드 날짜 (YYYY-MM-DD)
 * @param roundDates 완료된 라운드 날짜 목록 (`getRoundDates` 반환값 — 순서 무관)
 */
export function volumeForRound(date: string, roundDates: string[]): number | null {
  const asc = [...new Set(roundDates)].sort()
  const baseIdx = asc.indexOf(VOL_BASE_DATE)
  // 기준일이 완료 목록에 없으면(다른 리그 등) 계산 근거가 없다
  if (baseIdx === -1) return null

  const idx = asc.indexOf(date)
  if (idx !== -1) {
    // 완료된 라운드 — 기준일에서 몇 번째 떨어져 있는가
    const n = VOL_BASE_NUMBER + (idx - baseIdx)
    return n >= 1 ? n : null
  }

  // 완료 목록에 없는 라운드는 번호를 만들지 않는다.
  // 앞선 라운드가 아직 안 끝났으면 그 사이에 몇 개가 낄지 알 수 없어서, 세어 봐야 틀린 수가
  // 나온다(예: 08-15 가 미완료인 상태로 08-22 를 물으면 둘 다 VOL.4 가 나왔다).
  // 실제 사용 경로에서는 이 갈래에 오지 않는다 — 카드 생성기의 라운드 목록은 완료된 것만
  // 담고, 마감 직후 안내는 방금 끝난 날짜를 목록에 넣어서 묻는다.
  return null
}
